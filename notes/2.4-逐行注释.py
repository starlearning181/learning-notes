# ================================================================
# 第 0 部分：什么是导数（2.4 微积分的最小必需品）
# ================================================================
# 导数 = "x 变一点点，f(x) 跟着变多少" = 变化速度
# 直觉：开车时仪表盘上的"瞬时速度"就是距离对时间的导数

import torch

# 例子函数：f(x) = 3x^2 - 4x
def f(x):
    return 3 * x ** 2 - 4 * x

# 导数的定义：h 无限接近 0 时，(f(x+h) - f(x)) / h 的极限
# 我们没法真取 0，就用一个很小的 h 来"逼近"——数值法
h = 0.0001
x0 = 1.0
numerical = (f(x0 + h) - f(x0)) / h
print(numerical)        # ≈ 2.0001（真实导数 f'(x)=6x-4，在 x=1 处 = 2）
print(6 * x0 - 4)       # 2.0（解析解，精确值）
# 两者几乎一样 → 说明"逼近"这条路走得通
# 但深度学习有百万级参数，每个都用数值逼近太慢 → 于是有了"自动微分"

# ================================================================
# 第 1 部分：autograd 三板斧（2.5 的核心，就这三步）
# ================================================================
#   ① 声明：这个张量要记账（requires_grad）
#   ② 干活：用普通代码算出结果 y
#   ③ 回溯：y.backward() 自动算出 y 对 x 的梯度，存在 x.grad 里

x = torch.arange(4.0, requires_grad=True)   # ① 要记账的张量：[0,1,2,3]
print(x)                 # tensor([0., 1., 2., 3.], requires_grad=True)
print(x.grad)            # None（还没算过，没有账本）

y = 2 * torch.dot(x, x)  # ② y = 2 * x·x，即 y = 2x^2 的向量版 = 0+2+8+18 = 28
print(y)                 # tensor(28., grad_fn=<DotBackward0>)
# 注意 grad_fn：PyTorch 把"怎么算出来的"记成了链条，backward 时沿着它回溯

y.backward()             # ③ 回溯！自动算梯度
print(x.grad)            # tensor([0., 4., 8., 12.])
# 为什么？y = 2x²，导数 = 4x，代入 x=[0,1,2,3] → [0,4,8,12]
# ★ 你没有手推任何公式，PyTorch 替你求了导 —— 这就是 autograd

# ================================================================
# 第 2 部分：grad 会累加！—— 新手第一大坑
# ================================================================
# 再 backward 一次试试（不清理的话）：

y = x.sum()              # y = 0+1+2+3 = 6
y.backward()
print(x.grad)            # tensor([4., 5., 6., 7.])  ← 不是 [1,1,1,1]！
# 因为新梯度 [1,1,1,1] 累加到了旧的 [0,4,8,12] 上
# 所以每次新计算前必须手动清零：

x.grad.zero_()           # _ 结尾 = 原地修改（直接改 x.grad 本身）
y = x.sum()
y.backward()
print(x.grad)            # tensor([1., 1., 1., 1.])  ← 这次对了

# 记忆：backward 一次，清零一次。忘记清零 = 梯度越算越大 = 训练诡异

# ================================================================
# 第 3 部分：深一点的两个概念（看不懂可跳，混个脸熟）
# ================================================================

# 【分离 detach】把 y 从记账链条里"摘出来"，只当代数值用
x.grad.zero_()
y = x * x
u = y.detach()           # u 和 x 的计算图切断，之后 u 的变化不追责
z = u * x                # z = u * x，但只对 x 求导
z.sum().backward()
print(x.grad)            # tensor([0., 1., 4., 9.]) = u 的值
# 用处（现在记结论就行）：冻结一部分网络不训练时用 detach

# 【控制流也能求导】Python 的 if/while 混在计算里，autograd 照样能算
def f2(a):
    b = a * 2
    while b.norm() < 1000:   # 一直翻倍，直到够大
        b = b * 2
    if b.sum() > 0:
        c = b
    else:
        c = 100 * b
    return c

a = torch.randn(size=(), requires_grad=True)  # 随机一个标量
d = f2(a)
d.backward()
print(a.grad)            # 梯度 = d / a（想想为什么？提示：b=a*2^k，c 对 a 是线性）
print(a.grad == d / a)   # tensor(True) —— 自动验证了链式法则

