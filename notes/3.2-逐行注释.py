# ================================================================
# 1. l.sum().backward() 里的 .sum() 能不能去掉？为什么？
# 2. sgd() 里为什么必须写 p.grad.zero_()？
# 3. 如果把 lr 从 0.03 改成 3.0，训练会怎样？改成 0.000001 呢？
#
# 答案提示：
# 1. 不能。backward 只能从标量出发（昨天 2.5 实测报错：
#    grad can be implicitly created only for scalar outputs）
# 2. 梯度是累加的，不清零则下一批的梯度会叠加上去，参数更新量越滚越大
# 3. 太大（3.0）→ 步子迈太猛，损失震荡甚至变成 nan（发散）；
#    太小（1e-6）→ 3 个 epoch 几乎没前进，损失基本不动

