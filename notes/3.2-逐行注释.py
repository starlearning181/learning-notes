# ================================================================
# 第 0 部分：先用 3 句话搞懂 3.1 在讲什么（概念部分，无代码）
# ================================================================
# ① 模型：y = Xw + b     —— 假设答案 = 特征的加权和 + 一个偏置

# ② 损失：loss = (ŷ - y)² / 2   —— 猜得有多离谱，"越小越好"
# ③ 学习：不断微调 w 和 b，让损失变小（方法叫"梯度下降"）
#
# 三个角色记住这张表，后面所有代码都是在填这张表：
#   模型 f  → 拿什么猜       （linreg）
#   损失 L  → 怎么算错多少    （squared_loss）
#   优化器  → 怎么改参数      （sgd）
# ================================================================

import torch      # 张量 + 自动求导
import random     # 用来打乱数据顺序（普通 Python 库，不是 torch）

# 固定随机种子：让每次运行结果一模一样，方便你对照下面的"预期输出"
# （真实项目里有时也这么干，为了结果可复现；想体验"每次都不同"就删掉这两行）
torch.manual_seed(42)
random.seed(42)


# ================================================================
# 第 1 部分：造一份假数据 —— 我们知道标准答案，才能检验模型学没学会
# ================================================================
# 思路：先自己定好真值 w、b，再用它们生成 y，最后看模型能不能反推出来。
# 就像先藏好答案、再出题。

def synthetic_data(w, b, num_examples):
    """生成 y = Xw + b + 噪声，共 num_examples 个样本"""
    # torch.normal(均值, 标准差, 形状) = 按正态分布随机抽数
    # 形状 (1000, 2) = 1000 个样本，每个样本 2 个特征（比如"面积""房龄"）
    X = torch.normal(0, 1, (num_examples, len(w)))
    # X @ w 是矩阵乘法（2.3 学的 @）；+ b 是广播，给每一行都加上 b
    y = X @ w + b
    # 加一点噪声，模拟真实世界的测量误差（否则题目太完美、没有挑战）
    y += torch.normal(0, 0.01, y.shape)
    # reshape((-1, 1))：-1 表示"这一维我不想算，你自己推断"
    # 1000 个数 → (1000, 1) 的列向量，方便后面跟预测值对齐形状
    return X, y.reshape((-1, 1))


true_w = torch.tensor([2.0, -3.4])   # ★ 真值：这就是模型要"猜"的答案
true_b = 4.2
features, labels = synthetic_data(true_w, true_b, 1000)

print(features.shape)    # torch.Size([1000, 2])   1000 个样本 × 2 个特征
print(labels.shape)      # torch.Size([1000, 1])   每个样本 1 个答案
print(features[0])       # tensor([1.9269, 1.4873])  ← 第 1 个样本的特征
print(labels[0])         # tensor([2.9871])          ← 第 1 个样本的答案
# 手算验证：2.0*1.9269 + (-3.4)*1.4873 + 4.2 ≈ 2.9871 ✓ 对得上


# ================================================================
# 第 2 部分：小批量读取 —— 为什么不能一次喂 1000 个样本？
# ================================================================
# 三个原因（面试也常问）：
#   ① 一次算 1000 个样本的梯度太慢/太占显存
#   ② 用一小批就能"估算"出整体梯度方向，够用了
#   ③ 每批都不一样 → 天然的随机性，反而更容易跳出坏解
# 这就是"批量大小 batch_size"（超参数）的由来。

def data_iter(batch_size, features, labels):
    """把数据打乱后，按 batch_size 一批一批地吐出来"""
    num_examples = len(features)          # 1000
    indices = list(range(num_examples))    # [0, 1, 2, ..., 999]
    random.shuffle(indices)                # ★ 打乱！否则模型会记住顺序，学偏
    for i in range(0, num_examples, batch_size):
        # 取下标切片；min(...) 是防止最后一批越界（1000 不能被 10 整除时）
        batch_indices = torch.tensor(
            indices[i: min(i + batch_size, num_examples)])
        # ★ yield = 每次执行到这里就"交出"一批，函数暂停；
        #   下次再进来从暂停处继续。这叫"生成器"，好处是不用一次把所有
        #   批次都装进内存（100 万样本也扛得住）
        yield features[batch_indices], labels[batch_indices]


batch_size = 10
# for 循环配合生成器：每轮拿到一批，打印完就 break 看第一批长什么样
for X, y in data_iter(batch_size, features, labels):
    print(X.shape)   # torch.Size([10, 2])   ← 一批 10 个样本
    print(y.shape)   # torch.Size([10, 1])
    break            # 只看第一批，退出循环


# ================================================================
# 第 3 部分：初始化参数 —— 模型要"学"的就是这两个东西
# ================================================================
# 注意：初始值随便给（这里给很小），学习的过程会把它修正到接近真值。
# requires_grad=True 就是 2.5 学的"记账"：不记账就不会有梯度。

w = torch.normal(0, 0.01, size=(2, 1), requires_grad=True)  # 2 个特征 → 2 个权重
b = torch.zeros(1, requires_grad=True)                      # 偏置从 0 开始

print(w.shape)   # torch.Size([2, 1])   ← 形状必须能跟 X(10,2) 相乘
print(b.shape)   # torch.Size([1])


# ================================================================
# 第 4 部分：三件套 —— 模型 / 损失 / 优化器（各只有 2~5 行）
# ================================================================

def linreg(X, w, b):
    """模型：给定输入和参数，算出预测值"""
    return X @ w + b          # (10,2) @ (2,1) = (10,1)，正好跟 labels 同形状

def squared_loss(y_hat, y):
    """损失：平方误差再除以 2（除以 2 纯粹是为了求导后更简洁）"""
    return (y_hat - y.reshape(y_hat.shape)) ** 2 / 2
    # reshape 是保险措施：万一 y 形状不对，先掰成跟预测值一样，避免广播出错

def sgd(params, lr, batch_size):
    """优化器：随机梯度下降——沿着梯度反方向，把参数挪一小步"""
    with torch.no_grad():
        # ★ with torch.no_grad(): 意思是"接下来这段不要记账"
        #   因为我们是在手动改参数，不需要这些操作本身被求导
        #   不加它，PyTorch 会报错："a leaf Variable that requires grad
        #   is being used in an in-place operation"
        for p in params:
            # ★ 这行是深度学习的"心跳"：
            #   p - 学习率 × 梯度 / 批量大小
            #   ① 减号 = 往低处走（梯度指向上坡，所以反着走）
            #   ② lr 控制步子多大（太大震荡、太小太慢）
            #   ③ 除以 batch_size 是因为前面 l.sum() 是"求和"，
            #      除以 10 就变成"平均"，梯度尺度才稳定
            p -= lr * p.grad / batch_size
            # ★ 清空账本！2.5 学的累加坑：梯度是累加的，
            #   不清零的话下一轮算出来的是"两次的和"，会越跑越乱
            p.grad.zero_()


# ================================================================
# 第 5 部分：★ 训练循环 ★ —— 本章灵魂，也是全书最重要的 10 行
# ================================================================
# 请把下面这段背下来（不是背字，是背"顺序"）：

lr = 0.03           # 学习率：步子大小
num_epochs = 3      # epoch = 把整个数据集完整过几遍
net = linreg        # 给模型起个简称（书里这么写的，为了后面好引用）
loss = squared_loss

for epoch in range(num_epochs):                     # 外层：跑几遍全量数据
    for X, y in data_iter(batch_size, features, labels):   # 内层：一批一批取
        l = loss(net(X, w, b), y)                   # ① 前向：算预测值和损失
        # ★ 为什么 .sum()？—— 因为 l 是 (10,1) 的 10 个数，
        #   而 backward() 只能从"一个数"出发（昨天刚踩过的坑！）
        #   求和把 10 个数压成 1 个标量，才能反推
        l.sum().backward()                          # ② 反向：算出梯度存进 w.grad/b.grad
        sgd([w, b], lr, batch_size)                 # ③ 更新：按梯度挪一小步 + 清零

    # 每个 epoch 结束后，用全部数据评估一次（不加噪声地看纯误差）
    with torch.no_grad():                           # 只是看着玩，不需要记账
        train_l = loss(net(features, w, b), labels)
        print(f'epoch {epoch + 1}, loss {float(train_l.mean()):f}')

# 预期输出（固定了随机种子，你可以对一下）：
# epoch 1, loss 0.047187
# epoch 2, loss 0.000199
# epoch 3, loss 0.000050
# 看这个下降速度：0.047 → 0.0002 → 0.00005，一轮掉一个量级，模型学得很快


# ================================================================
# 第 6 部分：验收 —— 把学到的参数跟真值比一比
# ================================================================
print(f'w 的估计误差: {true_w - w.reshape(true_w.shape)}')
print(f'b 的估计误差: {true_b - b}')

# 预期输出：
# w 的估计误差: tensor([ 0.0006, -0.0002], grad_fn=<SubBackward0>)
# b 的估计误差: tensor([0.0001], grad_fn=<SubBackward0>)
# 误差都在千分之一量级 → 模型几乎完美地还原出了真值 [2.0, -3.4] 和 4.2

