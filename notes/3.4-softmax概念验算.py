"""
d2l 3.4 softmax 回归 —— 概念 + 数值验算
==================================================
说明：**3.4 这一节教材里没有代码**，全是概念和公式。
      所以这份文件是「把公式跑成数字」的验算脚本 —— 每个公式后面
      都能看到一个小张量验证它，看完你会对 3.6 从零实现少一半恐惧。

一句话抓住 3.4 在讲什么：
      回归「输出一个数」，分类「输出每类的概率」，所以最后一步必须换零件 ——
      换的是 ① 输出层加 softmax（变概率）  ② 损失换成交叉熵（量概率的错）

运行方式（WSL）：
   conda activate dl
   cd ~/code/learning-notes/notes
   python 3.4-softmax概念验算.py

实测输出（本机复现，全部经过实跑核对）：
   ① exp(o)          [[ 2.7183,  7.3891, 20.0855], [20.0855,  7.3891,  2.7183]]
   ② 每行求和         [[30.1929], [30.1929]]
   ③ softmax 输出     [[0.0900, 0.2447, 0.6652], [0.6652, 0.2447, 0.0900]]
      每行之和         [1.0, 1.0]        <-- 概率归一化成功
      最小值           0.09003...        <-- 非负
   ④ 交叉熵           0.40760597586631775
   ⑤ 独热编码         [[0., 0., 1.], [1., 0., 0.]]
"""

import torch


# ============================================================
# Part 0 · 先讲清楚：为什么分类不能用回归那一套
# ============================================================
# 假设三分类问题（猫 / 鸡 / 狗），教材举了三个「不能用」的理由：
#
#   ① 用编号当标签不合适：把「猫=1、鸡=2、狗=3」直接当数值，模型会以为
#      「狗 - 鸡 = 鸡 - 猫」，凭空造出大小和距离关系 —— 这是假的。
#   ② 输出一个数无法表达多个可能：一张模糊的图，可能 60% 是猫、30% 是狗，
#      单个数说不出这种「概率分布」。
#   ③ 回归用的平方损失对「概率」太苛刻：概率错一点点，惩罚却按平方放大。
#
# 所以改成：**输出 n 个类别各一个分数 → 变成概率 → 用交叉熵量错**。
#
#   one-hot 标签（下面 Part 4 验证）告诉模型「正确答案是哪一格」。


# ============================================================
# Part 1 · 原始输出 o（未归一化的分数，也叫 logits）
# ============================================================
# 用一个小例子代替整张图：2 个样本 × 3 个类别
#   第 1 行 [1, 2, 3] -> 模型对「类别 3」打分最高
#   第 2 行 [3, 2, 1] -> 模型对「类别 1」打分最高
o = torch.tensor([[1.0, 2.0, 3.0],
                  [3.0, 2.0, 1.0]])
print("原始输出 o（2 个样本 × 3 个类别）:\n", o)


# ============================================================
# Part 2 · softmax 三步：取指数 → 求和 → 相除
# ============================================================
# 公式：  softmax(o)ᵢ = exp(oᵢ) / Σⱼ exp(oⱼ)
#
# 为什么要「取指数」？
#   ① 保证非负：e^x 永远 > 0（负数也能变正数）
#   ② 放大差异：分数差 1，指数后差约 2.7 倍，让模型更「敢下判断」
#   ③ 不改变大小顺序：单调递增，原来分高的，指数后还是最高

exp_o = torch.exp(o)
print("\n① 取指数 exp(o):\n", exp_o)

# ★ 注意这一行的 keepdims=True —— 就是你 10/8 学的那条：
#   求和后「行」这一维不删除、保留成长度 1，形状是 (2,1)
#   这样下一步 (2,3) / (2,1) 才能广播成「每行除以自己的和」
#   如果写成 keepdims=False（或省略），得到 (2,)，就会报形状不匹配的错
partition = exp_o.sum(axis=1, keepdims=True)
print("\n② 每行求和（keepdims=True 保住 (2,1) 形状）:\n", partition)

y_hat = exp_o / partition
print("\n③ 相除 = softmax 输出:\n", y_hat)

# 验收两条「概率」的硬指标：
print("   每行之和:", y_hat.sum(axis=1).tolist(), " <-- 全 1 才叫概率分布")
print("   最小值  :", float(y_hat.min()), " <-- 非负")

# 怎么读结果：第 1 行 [0.09, 0.2447, 0.6652] 读作
#   「这个样本是类别 3 的概率 66.5%」—— 这就是分类的输出。


# ============================================================
# Part 3 · 交叉熵：只关心「正确那一类的概率」
# ============================================================
# 公式：  l(y, ŷ) = -Σ yᵢ · log(ŷᵢ)     （y 是 one-hot）
# 因为 one-hot 里只有一个 1，求和后只剩一项：
#         l = -log( 正确类的预测概率 )
#
# 直觉：预测正确的概率越接近 1，log 越接近 0，损失越小；
#       越接近 0，-log 越快冲向无穷大 —— 错得越离谱，罚得越狠。

y = torch.tensor([2, 0])            # 真实标签：第 1 个样本是类别 2，第 2 个是类别 0
print("\n真实标签 y =", y.tolist(), "（整数编号）")

# 取出「每个样本正确那一类」的预测概率：用高级索引一次拿完
pick = y_hat[torch.arange(2), y]
print("   正确类的预测概率:", pick.tolist())

ce = -torch.log(pick)
print("   交叉熵 -log(p)   :", ce.tolist())
print("   该批平均 loss    :", float(ce.mean()))
# 0.4076 怎么来的：-ln(0.6652) ≈ 0.4076，和上面数字对得上。

# 对照感受一下「罚得狠」：
#   若预测概率 0.9 -> 损失 0.105；若 0.1 -> 损失 2.303（差 22 倍）


# ============================================================
# Part 4 · 独热编码：3.4 说的 one-hot，就是你 2.2 玩过的 get_dummies
# ============================================================
# 教材在本节说「标签可以用 one-hot 表示」，它的实现是：
onehot = torch.nn.functional.one_hot(y, num_classes=3)
print("\n⑤ 独热编码 one_hot(y, num_classes=3):\n", onehot.float())
# 输出 [[0,0,1],[1,0,0]] —— 每行只有一个 1，就是「火柴只点着一头」

# 回想 2.2 那一节 pandas 的：
#   pd.get_dummies(inputs, dummy_na=True)   # 把文字列 Alley 拆成 0/1 列
# 两者是**同一个思想的两个应用场景**：
#   - get_dummies：把「特征」里的类别变数字（Pave / NaN -> 两列 0/1）
#   - one_hot    ：把「标签」里的类别变数字（类别 2 -> [0,0,1]）
# 差别只在 one_hot 的列顺序固定（按类别编号 0..n-1），不会乱序。


# ============================================================
# Part 5 · 自测三问（读完要能张口答）
# ============================================================
# Q1 分类问题为什么不能直接拿「类别编号 0/1/2」当训练目标？
#    A: 编号会凭空引入大小和距离关系（2 比 1 大、3-2 等于 2-1），
#       这些关系在类别之间并不存在，模型会学错。
#
# Q2 独热编码把标签变成了什么形状？
#    A: 从「一个整数」变成「长度 = 类别数的 0/1 向量」，
#       例如 3 类问题里 类别 2 -> [0, 0, 1]。
#
# Q3 softmax 怎么同时保证「非负」和「和为 1」？
#    A: 先取指数（e^x > 0 保证非负），再除以自己这一行的总和
#       （总和做分母，所以加起来必然是 1）。
#
# 一句话串起来：o -> softmax -> 概率 -> 与 one-hot 标签算交叉熵 -> loss
