"""
d2l 3.3 线性回归的简洁实现 —— 逐行注释
==================================================
对照物：你 10/2 亲手写的 3.2「从零实现」
一句话差别：3.2 是你自己造零件，3.3 是把零件换成现成的库，然后发现——
           架子完全一样，只是少了三行手动活。

★ 三个必须亲眼看到的差异（本文件里都标了【差异1/2/3】）
   1. l.backward() 前面没有 .sum()
   2. trainer.zero_grad() 挪到了 l.backward() 之前
   3. 最后那行 loss(net(features), labels) 是全量数据、且在内层循环外面

运行方式（WSL）：
   conda activate dl
   cd ~/code/learning-notes/notes
   python 3.3-逐行注释.py

实测输出（seed=42，本机复现，仅供参考）：
   一个批次的 X 形状: torch.Size([10, 2])
   w 初值: tensor([[-0.0053,  0.0103]]) | b 初值: tensor([0.])
   epoch 1, loss 0.000353
   epoch 2, loss 0.000103
   epoch 3, loss 0.000101
   w 的估计误差： tensor([-0.0002,  0.0008])
   b 的估计误差： tensor([-0.0007])
   ⚠️ 书上没写随机种子，你跑出来的数字一定不一样。
      只看两条：loss 单调下降 + 误差量级 < 0.01。
"""

# ============================================================
# Part 0 · 导包
# ============================================================
import torch                                    # 张量计算
from torch import nn                            # nn = 神经网络模块，装"现成零件"
from torch.utils import data                     # data = 数据加载工具（Dataset / DataLoader）

torch.manual_seed(42)                           # 固定随机种子 → 本文件所有随机数可复现
                                                # （教材没写这行，我加的，方便你对照数值）


# ============================================================
# Part 1 · 造数据（和 3.2 一模一样，直接照搬）
# ============================================================
def synthetic_data(w, b, num_examples):
    """生成 y = Xw + b + 噪声。真实参数 w,b 是我们知道的（方便最后验收）"""
    X = torch.normal(0, 1, (num_examples, len(w)))   # 1000×2 的标准正态特征
    y = X @ w + b                                     # @ 是矩阵乘：y 是 (1000,)
    y += torch.normal(0, 0.01, y.shape)               # 加极小噪声，模拟真实世界的测量误差
    return X, y.reshape((-1, 1))                      # y 从 (1000,) 拉成 (1000,1)，和模型输出对齐


true_w = torch.tensor([2, -3.4])                # 真值：答案卷
true_b = 4.2                                     # 真值：截距
features, labels = synthetic_data(true_w, true_b, 1000)   # 1000 个样本


# ============================================================
# Part 2 · 读数据：DataLoader（3.2 里是自己写的 data_iter）
# ============================================================
def load_array(data_arrays, batch_size, is_train=True):
    """把 (特征, 标签) 打包成 PyTorch 的 Dataset，再套一层 DataLoader"""
    dataset = data.TensorDataset(*data_arrays)   # *data_arrays 是解包：把 (features, labels) 拆成两个参数
                                                 # TensorDataset 把 X 和 y 按行"绑"在一起：第 i 组永远是配对的
    return data.DataLoader(dataset, batch_size, shuffle=is_train)
                                                 # shuffle=True：每轮打乱顺序（训练必须打乱，否则模型会记住"顺序"这种无关信息）
                                                 # DataLoader 自己管"分批"，不用你写 yield

batch_size = 10                                  # 每批 10 个样本
data_iter = load_array((features, labels), batch_size)   # 注意：它是个"可迭代对象"，不是列表
print('一个批次的 X 形状:', next(iter(data_iter))[0].shape)   # next(iter(...)) 手动取一批看看长啥样


# ============================================================
# Part 3 · 定义模型：nn.Sequential + nn.Linear（3.2 里是 net(X, w, b)）
# ============================================================
net = nn.Sequential(nn.Linear(2, 1))
# nn.Linear(2, 1) = 一个"全连接层"：输入 2 维 → 输出 1 维，内部藏着 w(2×1) 和 b(1)
#                  forward 时它自己算 X @ w.T + b，不用你写公式
# nn.Sequential(...) = 把多层"串"成一个流水线；现在只有一层，将来加层就往括号里塞
# net(X) 就是"喂数据、拿输出"，等价于你在 3.2 写的 net(X, w, b)


# ============================================================
# Part 4 · 初始化参数（★这里出现了"原地操作"）
# ============================================================
net[0].weight.data.normal_(0, 0.01)             # net[0] = 取第 0 层；.weight 是它的权重
                                                 # .data 是"脱离计算图的纯数值视图"（初始化不需要被 autograd 记账）
                                                 # normal_(0, 0.01) 尾部的下划线 = 原地操作：直接改自己，不新建张量
                                                 # 均值 0、标准差 0.01 的正态随机初值
net[0].bias.data.fill_(0)                        # 偏置填 0；fill_ 同样是原地操作
                                                 # （这就是昨天讲的"盖新房 vs 原地灌"，PyTorch 用尾下划线区分）


# ============================================================
# Part 5 · 损失函数：nn.MSELoss（3.2 里是手写的 squared_loss）
# ============================================================
loss = nn.MSELoss()
# 均方误差。关键：默认 reduction='mean' —— 它会先把每个样本的误差平方，再求平均，
# 最后交给你的是【一个标量】。
# 对比 3.2：你手写的 squared_loss 返回的是 (batch, 1) 的形状，每样本一个值，
#          所以你必须再 .sum() 才能 backward —— 这就是【差异 1】的根源。


# ============================================================
# Part 6 · 优化器：torch.optim.SGD（3.2 里是手写的 sgd 函数）
# ============================================================
trainer = torch.optim.SGD(net.parameters(), lr=0.03)
# net.parameters() = 让优化器"接管"模型里所有需要学的参数（这里就是 w 和 b）
#                   它会自己遍历、自己更新，你不必再手写 w -= lr * w.grad
# lr=0.03 = 学习率（和 3.2 保持一致，方便对比）


# ============================================================
# Part 7 · 训练循环（★和 3.2 逐行对照着看）
# ============================================================
num_epochs = 3                                   # 把全部数据扫 3 遍
for epoch in range(num_epochs):
    # ---------- 内层：一批一批地喂 ----------
    for X, y in data_iter:                       # DataLoader 自动分批 + 自动打乱
        l = loss(net(X), y)                      # 前向：net(X) 出预测 → 和真值 y 一起送进 MSELoss
                                                 #       得到的是【一个标量】l
        trainer.zero_grad()                      # 清零：把上一批留下的梯度归零
                                                 # ★【差异 2】位置变了！3.2 里你在 sgd() 内部清零，
                                                 #   这里被显式提到 backward 之前。
                                                 #   顺序铁律：zero_grad → backward → step
        l.backward()                             # 反向：从标量 l 出发，自动算出 w.grad / b.grad
                                                 # ★【差异 1】这里没有 .sum()！
                                                 #   因为 MSELoss 已经压成标量了，backward 可以直接出发。
                                                 #   3.2 要 .sum() 是因为手写损失返回的是向量。
        trainer.step()                           # 更新：优化器按 w -= lr * w.grad 挪一步

    # ---------- 外层：每轮结束，用全量数据报一次数 ----------
    l = loss(net(features), labels)              # ★【差异 3】注意三点：
                                                 #   ① 用的是 features/labels 全量，不是 X/y 那一个批次
                                                 #   ② 它在内层 for 的外面（每轮只跑一次，不是每批都跑）
                                                 #   ③ 没有 zero_grad / backward —— 只算数、不改参数
                                                 #   这条正是你 10/2 那个"单层循环 bug"的同款教训：
                                                 #   一旦这行掉进内层循环，它就变成"只看最后一批"。
    print(f'epoch {epoch + 1}, loss {l:f}')       # {:f} 默认保留 6 位小数，格式更干净


# ============================================================
# Part 8 · 验收：拿估计值和真值比
# ============================================================
w = net[0].weight.data                           # 取出训练完的 w
print('w 的估计误差：', true_w - w.reshape(true_w.shape))
# reshape(true_w.shape)：把 w 从 (1,2) 拉成 (2,)，才能和 true_w 逐元素相减
b = net[0].bias.data                             # 取出训练完的 b
print('b 的估计误差：', true_b - b)
# 误差越接近 0 越好。跑出来是千分之一量级说明模型学到了真参数。


# ============================================================
# 附 · 三个"改坏它"实验（每个 3 分钟，跑完就懂为什么）
# ============================================================
# 实验 1：trainer = torch.optim.SGD(net.parameters(), lr=3)      # lr 放大 100 倍
#         → loss 变成 nan 或巨大值。这叫"步长超过谷底宽度"，越走越远。
#
# 实验 2：num_epochs = 1
#         → loss 还停在 0.0x 量级。参数还没爬到谷底，迭代次数不够。
#
# 实验 3：把 trainer.zero_grad() 注释掉
#         → 梯度会一批批累加，等价于学习率越来越大，loss 开始乱跳。
#           这就是"梯度累加"的坑：不清零 ≠ 不更新，而是越更新越猛。
#
# 附加实验 4：batch_size 从 10 改成 1000（等于全批量梯度下降）
#         → 每轮只有 1 步，收敛慢但更稳。体会"批大小 ↔ 更新次数"的权衡。


